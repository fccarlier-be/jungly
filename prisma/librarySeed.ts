/**
 * Bibliothèque de plantes.
 *
 * IMPORTANT : ces profils sont des points de départ configurables, pas des
 * vérités scientifiques absolues -- les besoins réels dépendent du climat,
 * du substrat, de la taille du pot, de l'exposition, de la saison, de l'âge
 * et de l'état de la plante. L'utilisateur garde toujours la main pour les
 * ajuster.
 */

export interface LibraryWateringProfile {
  recurrenceType: "FIXED_INTERVAL_DAYS" | "INTERVAL_WEEKS";
  interval: number;
  waterAmount?: number;
  waterUnit?: "ml" | "L";
}

export interface LibraryFertilizingProfile {
  recurrenceType: "INTERVAL_WEEKS" | "INTERVAL_MONTHS";
  interval: number;
  activeFromMonth?: number;
  activeUntilMonth?: number;
}

export interface LibraryRepottingProfile {
  recurrenceType: "INTERVAL_MONTHS";
  interval: number;
}

export interface LibraryCareProfile {
  // Requis pour les 120 profils saisis a la main ; optionnels pour une fiche
  // importee depuis une source externe (ex. Perenual), qui ne documente pas
  // toujours tous ces champs -- mieux vaut les omettre que d'inventer une
  // valeur (temperature, humidite...) presentee comme un fait.
  exposure?: string;
  temperatureRange?: string;
  humidity?: string;
  substrate?: string;
  toxicity?: string;
  tips?: string;
  imageUrl?: string;
  /** Facile / Modéré / Exigeant -- fourni par certaines sources externes (ex. Perenual). */
  careLevel?: string;
  watering?: LibraryWateringProfile;
  fertilizing?: LibraryFertilizingProfile;
  repotting?: LibraryRepottingProfile;
}

